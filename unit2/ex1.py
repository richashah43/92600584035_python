num = 10

#IF STATEMENT

if num > 0:
    print("Number is positive")

#IF - ELSE STATEMENT
    
if num % 2 == 0 :
    print("Number is even")

else:
    print("Number is odd")


#IF-ELIF-ELSE STATEMENT

marks = 75

if marks >= 80:
    print("Grade A")
elif marks >= 60:
    print("Grade B")
else:
    print("Grade C")
