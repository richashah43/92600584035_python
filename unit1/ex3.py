a = 15
b = 5

print("\n ARITHMETIC OPERATORS ")
print("Addition =",a + b)
print("Substraction =",a - b)
print("Multiplication =",a * b)
print("Division =",a / b)
print("Modulus =",a % b)


print("\n RELATIONAL OPERATORS")
print("a == b :",a == b)
print("a != b :",a != b)
print("a > b :",a > b)
print("a < b :",a < b)
print("a >= b",a >= b)
print("a <= b",a <= b)


print("\n LOGICAL OPERATORS")
print((a > b) and (b < 10))
print((a < b) or (b < 10))
print(not(a < b))
